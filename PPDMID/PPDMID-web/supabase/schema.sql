create or replace function public.register_app_user(p_username text, p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  normalized_username text := lower(trim(p_username));
begin
  if normalized_username !~ '^[一-龥A-Za-z0-9_]{2,16}$' then
    raise exception '用户名须为 2–16 位中文、英文、数字或下划线。';
  end if;
  if char_length(p_password) < 6 then
    raise exception '密码至少需要 6 位。';
  end if;
  if exists (select 1 from public.app_users where username = normalized_username) then
    raise exception '该用户名已被注册，请换一个。';
  end if;

  insert into public.app_users (username, password_hash)
  values (normalized_username, extensions.crypt(p_password, extensions.gen_salt('bf', 10)));

  return jsonb_build_object('username', normalized_username);
end;
$$;

create or replace function public.login_app_user(p_username text, p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  matched_user public.app_users%rowtype;
  new_token uuid;
begin
  select * into matched_user
  from public.app_users
  where username = lower(trim(p_username));

  if not found or extensions.crypt(p_password, matched_user.password_hash) <> matched_user.password_hash then
    raise exception '用户名或密码不正确，请先注册或重新输入。';
  end if;

  delete from public.app_user_sessions where expires_at < now();
  insert into public.app_user_sessions (user_id)
  values (matched_user.id)
  returning session_token into new_token;

  update public.dashboard_stats
  set login_count = login_count + 1,
      updated_at = now()
  where id = 1;

  return jsonb_build_object(
    'id', matched_user.id,
    'username', matched_user.username,
    'session_token', new_token
  );
end;
$$;

create or replace function public.logout_app_user(p_session_token uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.app_user_sessions where session_token = p_session_token;
  return found;
end;
$$;

create or replace function public.save_diagnosis_history(
  p_session_token uuid,
  p_conversation_id text,
  p_crop text,
  p_growth_stage text,
  p_question text,
  p_answer text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id bigint;
  new_id bigint;
begin
  select user_id into current_user_id
  from public.app_user_sessions
  where session_token = p_session_token and expires_at > now();

  if current_user_id is null then
    raise exception '登录已失效，请重新登录。';
  end if;

  insert into public.diagnosis_history
    (user_id, conversation_id, crop, growth_stage, question, answer)
  values
    (current_user_id, nullif(trim(p_conversation_id), ''), trim(p_crop),
     trim(p_growth_stage), trim(p_question), trim(p_answer))
  returning id into new_id;

  update public.dashboard_stats
  set today_consults = case
        when consult_date = (now() at time zone 'Asia/Shanghai')::date then today_consults + 1
        else 1
      end,
      consult_date = (now() at time zone 'Asia/Shanghai')::date,
      updated_at = now()
  where id = 1;

  return new_id;
end;
$$;

create or replace function public.get_diagnosis_history(
  p_session_token uuid,
  p_limit integer default 20
)
returns table (
  id bigint,
  conversation_id text,
  crop text,
  growth_stage text,
  question text,
  answer text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id bigint;
begin
  select user_id into current_user_id
  from public.app_user_sessions
  where session_token = p_session_token and expires_at > now();

  if current_user_id is null then
    raise exception '登录已失效，请重新登录。';
  end if;

  return query
  select h.id, h.conversation_id, h.crop, h.growth_stage,
         h.question, h.answer, h.created_at
  from public.diagnosis_history h
  where h.user_id = current_user_id
  order by h.created_at desc
  limit greatest(1, least(coalesce(p_limit, 20), 50));
end;
$$;

create or replace function public.get_unread_alert_count(p_session_token uuid)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id bigint;
  unread_count bigint;
begin
  select user_id into current_user_id
  from public.app_user_sessions
  where session_token = p_session_token and expires_at > now();

  if current_user_id is null then
    raise exception '登录已失效，请重新登录。';
  end if;

  select count(*) into unread_count
  from public.alerts a
  where not exists (
    select 1 from public.app_user_alert_reads r
    where r.user_id = current_user_id and r.alert_id = a.id
  );

  return unread_count;
end;
$$;

create or replace function public.mark_alerts_read(p_session_token uuid)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id bigint;
  inserted_count bigint;
begin
  select user_id into current_user_id
  from public.app_user_sessions
  where session_token = p_session_token and expires_at > now();

  if current_user_id is null then
    raise exception '登录已失效，请重新登录。';
  end if;

  insert into public.app_user_alert_reads (user_id, alert_id)
  select current_user_id, a.id from public.alerts a
  on conflict (user_id, alert_id) do nothing;

  get diagnostics inserted_count = row_count;
  return inserted_count;
end;
$$;

