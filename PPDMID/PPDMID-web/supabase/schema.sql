  id bigint generated by default as identity primary key,
  username text not null unique check (username ~ '^[一-龥A-Za-z0-9_]{2,16}$'),
  password_hash text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.app_user_sessions (
  session_token uuid primary key default extensions.gen_random_uuid(),
  user_id bigint not null references public.app_users(id) on delete cascade,
  expires_at timestamptz not null default (now() + interval '30 days'),
  created_at timestamptz not null default now()
);

create index if not exists app_user_sessions_user_id_idx
  on public.app_user_sessions(user_id, expires_at desc);

create table if not exists public.diagnosis_history (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.app_users(id) on delete cascade,
  conversation_id text,
  crop text not null,
  growth_stage text not null,
  question text not null,
  answer text not null,
  created_at timestamptz not null default now()
